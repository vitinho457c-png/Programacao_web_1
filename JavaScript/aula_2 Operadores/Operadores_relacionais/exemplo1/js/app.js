 /*
 Operadores relacionais
 == -> igual
 === -> Estritamente Igual Valor e tipo
 != -> Diferente 
 > -> maior que
 < -> menor que 
 >= ->maior ou igual a
 <= -> menor ou igual a
 */
//Exemplos

let num1 = 7
let num2 = "7"
let num3=3

console.log(num1 == num2)//verifica apenas valor
console.log(num1 === num2)//verifica apenas valor e tipo
console.log(num1 != num2)//verifica apenas valor
console.log(num1 !== num2)//verifica apenas valor e tipo
console.log(num1 > num3)//verifica apenas valor maior
console.log(num1 < num3)
console.log(num1 >= num3)
console.log(num1 <= num3)
